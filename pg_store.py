"""PostgreSQL storage adapter for the office lab."""
import os

import psycopg
from psycopg.rows import dict_row

DSN = os.environ.get("OFFICE_PILOT_POSTGRES", "")


class Connection:
    def __init__(self):
        self.connection = psycopg.connect(DSN, row_factory=dict_row, options="-c search_path=lab08,public")

    def __enter__(self):
        self.connection.__enter__()
        return self

    def __exit__(self, *args):
        try:
            return self.connection.__exit__(*args)
        finally:
            self.connection.close()

    def execute(self, sql, args=()):
        return self.connection.execute(sql.replace("?", "%s"), args)


SCHEMA = """
CREATE SCHEMA IF NOT EXISTS lab08;
CREATE TABLE IF NOT EXISTS lab08.sessions (
    session_id text PRIMARY KEY, surname text NOT NULL, first_name text NOT NULL,
    group_name text NOT NULL, created_at text NOT NULL, expires_at text NOT NULL,
    token_hash text UNIQUE, employees_loaded integer NOT NULL DEFAULT 0,
    offices_loaded integer NOT NULL DEFAULT 0, processed_json text NOT NULL DEFAULT '[]',
    decision_json text, revision integer NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS lab08.events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id text NOT NULL REFERENCES lab08.sessions(session_id), occurred_at text NOT NULL,
    event_type text NOT NULL, employee_id text, detail_json text NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS events_session_idx ON lab08.events(session_id, event_id);
CREATE TABLE IF NOT EXISTS lab08.request_log (
    request_id text PRIMARY KEY, session_id text REFERENCES lab08.sessions(session_id),
    method text NOT NULL, path text NOT NULL, status_code integer NOT NULL,
    duration_ms double precision NOT NULL, occurred_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS request_log_session_idx ON lab08.request_log(session_id, occurred_at);
CREATE TABLE IF NOT EXISTS lab08.submissions (
    session_id text PRIMARY KEY REFERENCES lab08.sessions(session_id),
    result text NOT NULL CHECK(result IN ('passed','not_passed')), submitted_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS lab08.notifications (
    notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id text NOT NULL REFERENCES lab08.sessions(session_id), result text NOT NULL,
    text text NOT NULL, delivery_status text NOT NULL DEFAULT 'pending',
    attempt_count integer NOT NULL DEFAULT 0, last_error text, claimed_at text,
    created_at text NOT NULL, sent_at text
);
CREATE SCHEMA IF NOT EXISTS course_events;
CREATE TABLE IF NOT EXISTS course_events.events (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source text NOT NULL, attempt_id text NOT NULL, kind text NOT NULL,
    occurred_at text NOT NULL, payload jsonb NOT NULL, imported boolean NOT NULL DEFAULT false,
    UNIQUE (source, attempt_id, kind)
);
CREATE TABLE IF NOT EXISTS course_events.deliveries (
    event_id bigint NOT NULL REFERENCES course_events.events(id),
    consumer text NOT NULL, status text NOT NULL, receipt_id text NOT NULL,
    PRIMARY KEY (event_id, consumer)
);
"""


def initialize():
    with psycopg.connect(DSN) as connection:
        connection.execute(SCHEMA)


def publish(connection, state, kind, occurred_at, *, imported=False):
    row = connection.execute(
        """INSERT INTO course_events.events(source,attempt_id,kind,occurred_at,payload,imported)
           VALUES ('lab08',?,?,?,?,?) ON CONFLICT (source,attempt_id,kind) DO NOTHING RETURNING id""",
        (state["session_id"], kind, occurred_at,
         psycopg.types.json.Jsonb({"surname": state["surname"], "first_name": state["first_name"],
                                   "group_name": state["group_name"]}), imported),
    ).fetchone()
    if row:
        connection.execute("SELECT pg_notify('course_events', ?)", (str(row["id"]),))
